# - Exercício 3: Área de um retângulo
# - Descrição: Faça um programa que solicite a largura e o comprimento de um terreno retangular. Calcule e 
# apresente sua área em metros quadrados. 

print("===EXERCÍCIO 3===")

# - Entrada de dados
lar = int(input("Digite a largura do terreno: "))
com = int(input("Digite o comprimento do terreno: "))

# - Cálculo da área
area = lar * com
print(f"A área do terreno é {area} metros quadrados")


