# - Exercício 2: Conversão de metros para centímetros
# - Descrição: Faça um programa que solicite uma medida em metros e converta essa medida para centímetros. 

print("===Exercício 02===")
# - Entrada de dados
med = float(input("Digite uma medida em metros: "))
cal = med * 100

# - Saída dos dados
print(f"{med} metros correspondem a {cal} centímetros")
